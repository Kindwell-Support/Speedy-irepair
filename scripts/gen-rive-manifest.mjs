#!/usr/bin/env node
// Scans public/rive/*.riv and writes src/components/rive/available.generated.ts.
// Runs on predev/prebuild, so dropping `public/rive/<icon-id>.riv` switches that
// icon from the SVG fallback to Rive with NO code change.
import { readdirSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "public", "rive");
const out = join(root, "components", "rive", "available.generated.ts");
const ids = existsSync(dir)
  ? readdirSync(dir).filter((f) => f.endsWith(".riv")).map((f) => f.replace(/\.riv$/, "")).sort()
  : [];
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/gen-rive-manifest.mjs — do not edit.\n` +
    `// .riv files present in public/rive at build time.\n` +
    `export const AVAILABLE_RIV: ReadonlySet<string> = new Set(${JSON.stringify(ids)});\n`,
);
console.log(`[rive] ${ids.length} .riv file(s): ${ids.join(", ") || "(none — SVG fallbacks in use)"}`);
